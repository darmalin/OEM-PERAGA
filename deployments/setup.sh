#!/usr/bin/env bash
# Server setup for staging or production (see deployments/PRODUCTION.md).
#
#   deployments/setup.sh init staging|prod   write .env with fresh secrets (run once per clone)
#   deployments/setup.sh check               check .env before starting the stack
#
# Run from the repository root. Secrets are written straight into .env and never printed.
set -euo pipefail

cd "$(dirname "$0")/.."
ENV_FILE=.env

die() { echo "error: $*" >&2; exit 1; }
rand_hex() { openssl rand -hex 24; }
# Fernet key: 32 random bytes, URL-safe base64.
fernet_key() { openssl rand -base64 32 | tr '+/' '-_'; }

init() {
  local target="${1:-}"
  local project port environment cookie
  case "$target" in
    staging) project=ems-staging; port=8080; environment=staging; cookie=ems_staging_session ;;
    prod) project=ems-prod; port=8081; environment=production; cookie=ems_session ;;
    *) die "usage: deployments/setup.sh init staging|prod" ;;
  esac
  command -v openssl >/dev/null || die "openssl is required"
  command -v docker >/dev/null || die "docker is required"
  [[ -e "$ENV_FILE" ]] && die "$ENV_FILE already exists; move it away first (it holds the encryption key)"

  umask 077
  cat > "$ENV_FILE" <<EOF
# EMS $target. Generated by deployments/setup.sh on $(date -u +%Y-%m-%d).
# Fill every placeholder value (deployments/setup.sh check lists them); the rest are ready.
# Back up this file (password manager): EMS_APP_ENCRYPTION_KEY cannot be recovered.

# --- Compose: production files only, one project per environment
COMPOSE_FILE=compose.yaml
COMPOSE_PROJECT_NAME=$project
# Only the host nginx reaches the app; never 0.0.0.0.
EMS_HTTP_PORT=127.0.0.1:$port

# --- Infrastructure (generated)
POSTGRES_USER=ems
POSTGRES_DB=ems
POSTGRES_PASSWORD=$(rand_hex)
STORAGE_ACCESS_KEY=$(rand_hex)
STORAGE_SECRET_KEY=$(rand_hex)

# --- Application
EMS_ENVIRONMENT=$environment
EMS_LOG_LEVEL=INFO
EMS_APP_ENCRYPTION_KEY=$(fernet_key)
# The address people open, with https://. Used in links inside emails.
EMS_PUBLIC_BASE_URL=https://CHANGE_ME
EMS_SESSION_COOKIE_NAME=$cookie
EMS_SESSION_COOKIE_SECURE=true
EMS_SESSION_IDLE_TIMEOUT_SECONDS=7200
EMS_SESSION_ABSOLUTE_TIMEOUT_SECONDS=43200
EMS_REPORT_TIMEZONE=Asia/Jakarta

# --- Email fallback. The default account under System > Email Accounts is used first;
# these are only used while none is set. Staging: use a sandbox, not real visitors' inboxes.
EMS_EMAIL_BACKEND=smtp
EMS_SMTP_HOST=CHANGE_ME
EMS_SMTP_PORT=587
EMS_SMTP_USE_TLS=true
EMS_SMTP_USERNAME=CHANGE_ME
EMS_SMTP_PASSWORD=CHANGE_ME
EMS_EMAIL_FROM=EMS <no-reply@CHANGE_ME>

# --- Limits
EMS_IMPORT_MAX_BYTES=20971520
EMS_IMPORT_MAX_ROWS=100000
EMS_SCANNER_CACHE_TTL_SECONDS=43200
EOF

  echo "Wrote $ENV_FILE for $target (project $project, app on 127.0.0.1:$port)."
  echo
  echo "Next:"
  echo "  1. Edit $ENV_FILE and fill every CHANGE_ME:"
  grep -n "^[A-Z_]*=.*CHANGE_ME" "$ENV_FILE" | sed 's/^/       line /'
  echo "  2. Save a copy of $ENV_FILE in the team password manager."
  echo "  3. Host nginx: deployments/nginx/host-site.conf.example (port $port)."
  echo "  4. deployments/setup.sh check"
  echo "  5. docker compose up -d --build"
  echo "     docker compose run --rm api python -m app.cli create-superuser"
}

check() {
  [[ -f "$ENV_FILE" ]] || die "no $ENV_FILE; run: deployments/setup.sh init staging|prod"
  local problems=0
  warn() { echo "  ✗ $*"; problems=$((problems + 1)); }
  ok() { echo "  ✓ $*"; }
  get() { grep -E "^$1=" "$ENV_FILE" | tail -1 | cut -d= -f2-; }

  echo "Checking $ENV_FILE"
  if grep -q "^[A-Z_]*=.*CHANGE_ME" "$ENV_FILE"; then
    warn "still to fill: $(grep -o '^[A-Z_]*=.*CHANGE_ME' "$ENV_FILE" | cut -d= -f1 | tr '\n' ' ')"
  else
    ok "no CHANGE_ME left"
  fi
  [[ "$(get COMPOSE_FILE)" == "compose.yaml" ]] && ok "COMPOSE_FILE=compose.yaml" \
    || warn "COMPOSE_FILE must be compose.yaml (else the dev override loads)"
  [[ -n "$(get COMPOSE_PROJECT_NAME)" ]] && ok "project $(get COMPOSE_PROJECT_NAME)" \
    || warn "COMPOSE_PROJECT_NAME is empty"
  [[ "$(get EMS_HTTP_PORT)" == 127.0.0.1:* ]] && ok "app bound to $(get EMS_HTTP_PORT)" \
    || warn "EMS_HTTP_PORT should be 127.0.0.1:<port>"
  case "$(get EMS_ENVIRONMENT)" in
    staging|production) ok "EMS_ENVIRONMENT=$(get EMS_ENVIRONMENT)" ;;
    *) warn "EMS_ENVIRONMENT must be staging or production" ;;
  esac
  [[ "$(get EMS_APP_ENCRYPTION_KEY)" =~ ^[A-Za-z0-9_-]{43}=$ ]] && ok "encryption key looks valid" \
    || warn "EMS_APP_ENCRYPTION_KEY is not a Fernet key"
  [[ "$(get EMS_PUBLIC_BASE_URL)" == https://* && "$(get EMS_PUBLIC_BASE_URL)" != *CHANGE_ME* ]] && ok "public URL $(get EMS_PUBLIC_BASE_URL)" \
    || warn "EMS_PUBLIC_BASE_URL should start with https://"
  for k in POSTGRES_PASSWORD STORAGE_SECRET_KEY; do
    local v; v="$(get "$k")"
    [[ ${#v} -ge 24 && "$v" != change-me* ]] && ok "$k set" || warn "$k is weak or a placeholder"
  done
  local perms; perms="$(stat -c %a "$ENV_FILE")"
  [[ "$perms" == 600 ]] && ok "$ENV_FILE is private (600)" || warn "chmod 600 $ENV_FILE (now $perms)"
  if docker compose config --services 2>/dev/null | grep -qx mailpit; then
    warn "dev services (mailpit) would start: the override file is loaded"
  else
    ok "production services only"
  fi

  echo
  if (( problems )); then
    echo "$problems problem(s). Fix them before docker compose up."
    exit 1
  fi
  echo "Ready: docker compose up -d --build"
}

case "${1:-}" in
  init) init "${2:-}" ;;
  check) check ;;
  *) die "usage: deployments/setup.sh init staging|prod | check" ;;
esac
